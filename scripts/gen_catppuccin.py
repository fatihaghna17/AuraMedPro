# Generates Catppuccin overrides for Tailwind v4 color tokens:
#   - Mocha (accent Sapphire) scoped to html.dark  -> src/catppuccin-mocha.css
#   - Latte (accent Sapphire) scoped to html.light -> src/catppuccin-latte.css
# Usage: python3 scripts/gen_catppuccin.py src
import sys, os

STD = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
FAMS_NEUTRAL = ['slate', 'gray', 'zinc', 'neutral', 'stone']

def rgb(h): h = h.lstrip('#'); return [int(h[i:i+2], 16) for i in (0, 2, 4)]
def mix(a, b, t):
    A, B = rgb(a), rgb(b)
    return '#' + ''.join(f'{round(x*t + y*(1-t)):02x}' for x, y in zip(A, B))

def accent_map(P):
    return dict(indigo=P['sapphire'], blue=P['sapphire'], sky=P['sky'], cyan=P['sky'], teal=P['teal'],
                violet=P['mauve'], purple=P['mauve'], fuchsia=P['pink'], pink=P['pink'],
                rose=P['red'], red=P['red'], orange=P['peach'], amber=P['yellow'], yellow=P['yellow'],
                lime=P['green'], green=P['green'], emerald=P['green'])

def emit(scope, title, P, neutral, scale, extra_vars, extra_css):
    o = ['/* ===================================================================',
         f' * Catppuccin {title} (accent: Sapphire) - palette remap for {scope}.',
         ' * Tailwind v4 utilities resolve colours through --color-* variables,',
         ' * so overriding them here re-themes every utility class without',
         ' * touching component code. Generated by scripts/gen_catppuccin.py - do not edit by hand.',
         ' * =================================================================== */',
         f'{scope} {{']
    for k, v in P.items(): o.append(f'  --ctp-{k}: {v};')
    o.append('')
    for fam in FAMS_NEUTRAL:
        for s, v in neutral.items():
            if fam != 'slate' and s not in STD: continue
            o.append(f'  --color-{fam}-{s}: {v};')
    o.append('')
    for fam, c in accent_map(P).items():
        for s, v in scale(c).items(): o.append(f'  --color-{fam}-{s}: {v};')
    sc, rs = scale(P['sapphire']), scale(P['red'])
    o += [f'  --color-indigo-650: {sc[600]};', f'  --color-rose-455: {rs[400]};', f'  --color-rose-555: {rs[500]};']
    o += extra_vars(P, sc)
    o.append('}')
    o += extra_css(P)
    return '\n'.join(o) + '\n'

# ---------------- Mocha (dark) ----------------
MOCHA = dict(rosewater='#f5e0dc', flamingo='#f2cdcd', pink='#f5c2e7', mauve='#cba6f7',
             red='#f38ba8', maroon='#eba0ac', peach='#fab387', yellow='#f9e2af',
             green='#a6e3a1', teal='#94e2d5', sky='#89dceb', sapphire='#74c7ec',
             blue='#89b4fa', lavender='#b4befe', text='#cdd6f4', subtext0='#a6adc8',
             overlay1='#7f849c', surface0='#313244', base='#1e1e2e', mantle='#181825', crust='#11111b')
MOCHA_NEUTRAL = {50: '#e3e8fa', 100: '#cdd6f4', 200: '#bac2de', 250: '#b0b8d3', 300: '#a6adc8', 350: '#a6adc8',
                 400: '#9399b2', 450: '#9399b2', 500: '#7f849c', 600: '#585b70', 655: '#585b70',
                 700: '#45475a', 750: '#45475a', 800: '#313244', 805: '#313244', 850: '#313244',
                 900: '#1e1e2e', 905: '#1e1e2e', 950: '#181825'}
def mocha_scale(c):
    w, b = '#ffffff', MOCHA['base']
    return {50: mix(c, w, .3), 100: mix(c, w, .45), 200: mix(c, w, .65), 300: mix(c, w, .85),
            400: c, 500: c, 600: mix(c, b, .85), 700: mix(c, b, .7), 800: mix(c, b, .5),
            900: mix(c, b, .35), 950: mix(c, b, .22)}
def mocha_vars(P, sc):
    return ['', '  --color-brand-bg: #1e1e2e;', '  --color-brand-surface: #313244;',
            '  --color-brand-surface-hover: #45475a;', '  --color-brand-border: #45475a;',
            '  --color-brand-border-subtle: #313244;', f"  --color-brand-primary: {P['sapphire']};",
            f'  --color-brand-primary-hover: {sc[600]};', f"  --color-brand-secondary: {P['blue']};",
            '  --color-brand-text: #cdd6f4;', '  --color-brand-text-muted: #a6adc8;',
            '  --color-brand-text-faint: #7f849c;', f"  --color-brand-xp: {P['yellow']};"]
def mocha_css(P):
    # Mocha accents are pastel: white text on solid accent fills has poor contrast,
    # so use Crust for text (as official Catppuccin ports do).
    sel = []
    for f in accent_map(P):
        for s in (400, 500, 600):
            for p in ('bg', 'from'):
                sel.append(f'html.dark .text-white:is([class*="{p}-{f}-{s} "], [class$="{p}-{f}-{s}"])')
    return ['', '/* Pastel accents: dark text on solid accent fills for contrast. */',
            ',\n'.join(sel) + ' {\n  color: var(--ctp-crust);\n}']

# ---------------- Latte (light) ----------------
